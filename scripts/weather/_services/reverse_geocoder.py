EMOJIS = ["🏙️", "🏖️", "🏔️", "🌧️", "❄️", "🌊", "🏜️", "🌋", "🌁", "🌃"]

def reverse_geocode(lat: float, lon: float) -> str:
    """
    Возвращает 'Страна, Местность' по координатам.
    """
    # Простая симуляция: случайный выбор из списка
    country, city = random.choice(REGIONS)
    return f"{country}, {city}"

def get_location_emoji() -> str:
    """Возвращает случайный эмодзи из набора."""
    return random.choice(EMOJIS)